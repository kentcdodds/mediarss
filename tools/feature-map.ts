import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { routes } from '#app/routes.ts'
import {
	featureNotes,
	type FeatureNote,
	type FeatureSurface,
	type RouteName,
} from './feature-notes.ts'

export const featureMapPath = path.join(
	import.meta.dirname,
	'..',
	'.agents/skills/control-mediarss/references/feature-map.md',
)

export type FeatureEntry = FeatureNote & {
	name: RouteName
	method: string
	pattern: string
}

const surfaceOrder: Array<FeatureSurface> = [
	'page',
	'admin-api',
	'public',
	'oauth',
	'mcp',
	'ops',
]

const surfaceTitles: Record<FeatureSurface, string> = {
	page: 'Admin pages',
	'admin-api': 'Admin API',
	public: 'Public feed, media, and art (podcast apps)',
	oauth: 'OAuth',
	mcp: 'MCP',
	ops: 'Operations',
}

export function getFeatureEntries(): Array<FeatureEntry> {
	const notes: Record<string, FeatureNote> = featureNotes
	return Object.entries(routes).map(([name, route]) => {
		const note = notes[name]
		if (!note) throw new Error(`No feature note for route "${name}"`)
		return {
			...note,
			name: name as RouteName,
			method: route.method,
			pattern: route.pattern.source,
		}
	})
}

export function findFeature(query: string): Array<FeatureEntry> {
	const needle = query.toLowerCase()
	return getFeatureEntries().filter(
		(entry) =>
			entry.name.toLowerCase().includes(needle) ||
			entry.pattern.toLowerCase().includes(needle),
	)
}

function escapeCell(text: string) {
	return text.replaceAll('|', '\\|')
}

export function renderFeatureMap(): string {
	const entries = getFeatureEntries()
	const lines = [
		'# Feature Map',
		'',
		'<!-- Generated by `npm run --silent control -- map --write` from app/routes.ts',
		'and tools/feature-notes.ts. Do not edit by hand; CI checks this through',
		'`npm test`. -->',
		'',
		'Every route in `app/routes.ts`, with how to seed and reach it from the',
		'control environment (`npm run --silent control -- dev`). Commands are',
		'`control-mediarss` subcommands. **High** routes always need Kent.',
		'',
	]
	for (const surface of surfaceOrder) {
		const group = entries.filter((entry) => entry.surface === surface)
		if (group.length === 0) continue
		lines.push(`## ${surfaceTitles[surface]}`, '')
		lines.push('| Route | Pattern | Methods | What | Seed | Reach | High |')
		lines.push('| --- | --- | --- | --- | --- | --- | --- |')
		for (const entry of group) {
			const methods =
				entry.method === 'ANY' ? (entry.methods ?? 'ANY') : entry.method
			lines.push(
				`| \`${entry.name}\` | \`${entry.pattern}\` | ${methods} | ${escapeCell(entry.summary)} | ${escapeCell(entry.seed ?? '-')} | \`${escapeCell(entry.reach)}\` | ${entry.high ? 'yes' : ''} |`,
			)
		}
		lines.push('')
	}
	return lines.join('\n')
}

export async function writeFeatureMap() {
	await mkdir(path.dirname(featureMapPath), { recursive: true })
	await writeFile(featureMapPath, renderFeatureMap())
}

export async function checkFeatureMap(): Promise<Array<string>> {
	const problems: Array<string> = []
	const routeNames = new Set(Object.keys(routes))
	for (const name of Object.keys(featureNotes)) {
		if (!routeNames.has(name)) {
			problems.push(
				`tools/feature-notes.ts has a note for "${name}", which app/routes.ts no longer exports`,
			)
		}
	}
	const notes: Record<string, FeatureNote> = featureNotes
	for (const name of routeNames) {
		if (!notes[name]) {
			problems.push(
				`app/routes.ts exports "${name}" but tools/feature-notes.ts has no note for it`,
			)
		}
	}
	if (problems.length > 0) return problems

	const committed = await readFile(featureMapPath, 'utf8').catch(() => null)
	if (committed !== renderFeatureMap()) {
		problems.push(
			`${path.relative(process.cwd(), featureMapPath)} is stale; run \`npm run --silent control -- map --write\``,
		)
	}
	return problems
}
